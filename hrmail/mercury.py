"""Mercury modem: sound-device discovery and mercury.ini generation."""

import re
import subprocess
from dataclasses import dataclass
from pathlib import Path

from . import radios
from .settings import Settings

ARQ_PORT = 8300  # control; data is ARQ_PORT + 1 (VARA-compatible)

_DEVICE_RE = re.compile(r"name:\s*'(?P<name>.*?)'\s+id:\s*'(?P<id>.*?)'(?P<default>\s*\(system default\))?")


@dataclass
class AudioDevice:
    name: str
    id: str
    is_default: bool = False


def parse_devices(text: str) -> tuple[list[AudioDevice], list[AudioDevice]]:
    """Parse `mercury -z` output into (playback, capture) device lists."""
    playback: list[AudioDevice] = []
    capture: list[AudioDevice] = []
    current = None
    for line in text.splitlines():
        lower = line.strip().lower()
        if lower.startswith("playback devices"):
            current = playback
            continue
        if lower.startswith("capture devices"):
            current = capture
            continue
        match = _DEVICE_RE.search(line)
        if match and current is not None:
            current.append(AudioDevice(match["name"].strip(), match["id"], bool(match["default"])))
    return playback, capture


def list_devices(mercury_exe: Path, timeout: float = 20) -> tuple[list[AudioDevice], list[AudioDevice]]:
    result = subprocess.run(
        [str(mercury_exe), "-z"],
        cwd=str(mercury_exe.parent),
        capture_output=True,
        text=True,
        encoding="utf-8",
        errors="replace",
        timeout=timeout,
        creationflags=_no_window(),
    )
    return parse_devices(result.stdout + "\n" + result.stderr)


def pick_radio_device(devices: list[AudioDevice]) -> AudioDevice | None:
    """The radio's USB sound card, or None if there is not exactly one candidate."""
    for needle in ("usb audio codec", "usb"):
        matches = [d for d in devices if needle in d.name.lower()]
        if len(matches) == 1:
            return matches[0]
        if len(matches) > 1:
            return None
    return None


def render_ini(settings: Settings) -> str:
    """Complete mercury.ini for hr-mail. Anything not listed uses Mercury's defaults."""
    lines = [
        "; Generated by hr-mail on every start. Do not edit: changes are overwritten.",
        "[main]",
        "ui_enabled = false",
        f"input_device = {settings.input_device}",
        f"output_device = {settings.output_device}",
        "capture_channel = left",
        "sound_system = auto",
        f"arq_tcp_base_port = {ARQ_PORT}",
        "",
        "[ptt]",
    ]
    lines += ptt_lines(settings)
    lines += [
        "",
        "[store]",
        "; hr-mail keeps messages in Pat's mailbox, not in Mercury's chat store.",
        "enabled = false",
        "",
    ]
    return "\n".join(lines)


def ptt_lines(s: Settings) -> list[str]:
    """The [ptt] section body for the chosen radio connection."""
    if s.ptt_method == radios.PTT_CAT:
        lines = [
            "method = hamlib",
            f"device = {s.com_port}",
            f"hamlib_model = {s.hamlib_model}",
            f"hamlib_serial_speed = {s.baud}",
        ]
        if s.civ_addr:
            lines.append(f"hamlib_conf = civaddr={s.civ_addr}")
        return lines
    if s.ptt_method == radios.PTT_SERIAL:
        return [
            "method = serial",
            f"device = {s.com_port}",
            f"line = {s.serial_line}",
            f"invert = {s.serial_invert}",
        ]
    if s.ptt_method == radios.PTT_CM108:
        # Mercury finds the CM108 HID device on its own.
        return ["method = cm108", f"cm108_gpio = {s.cm108_gpio}"]
    return ["method = none"]  # VOX: the radio keys itself on audio


def command(mercury_exe: Path, ini_path: Path) -> list[str]:
    return [str(mercury_exe), "-C", str(ini_path)]


def _no_window() -> int:
    return getattr(subprocess, "CREATE_NO_WINDOW", 0)
